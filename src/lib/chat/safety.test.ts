import { describe, expect, it } from "vitest";
import { detectEmergency } from "./safety";

describe("detectEmergency", () => {
  it.each([
    ["I can smell gas in my kitchen", "gas"],
    ["there's a gas smell upstairs", "gas"],
    ["It smells of gas", "gas"],
    ["smell of gas near the meter", "gas"],
    ["I think we have a gas leak", "gas"],
    ["the pipe is leaking gas", "gas"],
    ["CARBON MONOXIDE alarm beeping", "gas"],
    ["my co alarm is going off", "gas"],
    ["CO detector keeps sounding", "gas"],
    ["my boiler is on fire", "fire"],
    ["there is a fire in the airing cupboard", "fire"],
    ["flames coming from the boiler", "fire"],
    ["smoke coming out of the boiler", "fire"],
    ["There is water pouring over the fuse box", "electric"],
    ["flooding near the electrics", "electric"],
    ["my kitchen is flooded and the sockets are under water", "electric"],
    ["water leaking onto the consumer unit", "electric"],
    ["leak dripping on the plug socket", "electric"],
    // Wordings a fresh reviewer found the first version missed.
    ["carbon-monoxide alarm is beeping", "gas"],
    ["monoxide alarm keeps going", "gas"],
    ["my CO-alarm went off", "gas"],
    ["there is a gas odour in the hall", "gas"],
    ["I can catch the scent of gas", "gas"],
    ["rotten egg smell by my boiler and I feel dizzy", "gas"],
    ["smells like rotten eggs", "gas"],
    ["the gas is hissing", "gas"],
    ["boiler fumes in the kitchen", "gas"],
    ["fumes from my boiler", "gas"],
    ["I get dizzy when the boiler is on", "gas"],
    ["headaches whenever the heating runs", "gas"],
    ["yellow flame on my boiler", "gas"],
    ["smoke alarm is going off", "fire"],
    ["burning smell from my boiler", "fire"],
    ["a smell of burning in the airing cupboard", "fire"],
    ["sparks from the socket", "fire"],
    ["fire in my kitchen", "fire"],
    ["water coming through my light switch", "electric"],
    ["co2 alarm is beeping", "gas"],
    ["my alarm by the boiler is going off", "gas"],
    ["Smell in the kitchen. I think it is gas", "gas"],
    ["i smell gass", "gas"],
    ["soot and black marks around my boiler", "gas"],
    ["fuga de gas", "gas"],
    ["J'ai une odeur de gaz", "gas"],
    ["wyciek gazu", "gas"],
    ["my boiler exploded", "fire"],
    ["water dripping from the light", "electric"],
    ["water pouring into the plug", "electric"],
    ["flood near the fuses", "electric"],
    ["water on the electric meter", "electric"],
    ["got an electric shock from the tap", "electric"],
    ["do you know what to do, my CO alarm is beeping", "gas"],
  ])("flags %s", (text, kind) => {
    expect(detectEmergency(text)).toBe(kind);
  });

  it.each([
    "How much is a boiler service?",
    "Do you service gas boilers?",
    "How much is my gas bill likely to drop with a new boiler?",
    "Do you fit fireplaces?",
    "My hot water tap is dripping",
    "Do you cover Westhill?",
    "I want an electric shower fitted",
    "Can you co-ordinate with my kitchen fitter?",
    "We are on the second floor of a block",
    "firewall settings for my smart thermostat",
    "My water bill is high",
    "My pilot flame has gone out",
    "Do you fit smoke alarms?",
    "How much is a new gas boiler?",
    "Do you fix leaks on gas boilers?",
    "Do you fit carbon monoxide alarms?",
    "does a service check for gas leaks?",
    "can you fit a fire surround",
    "Do you check for carbon monoxide during a service?",
    "how much to move a socket away from a leaking tap",
    "Is there a charge for a gas leak check?",
    "my bath plug is leaking water",
    "the plug in my sink lets the water out",
    "the boiler light is on and it is leaking water",
    "a light drip of water from the tap",
  ])("leaves alone %s", (text) => {
    expect(detectEmergency(text)).toBeNull();
  });
});
